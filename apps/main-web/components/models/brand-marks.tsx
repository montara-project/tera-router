/** A model's brand mark in the brand's colour, or null when its brand is unknown. */
export function modelBrandIcon(id: string, group?: string) {
  // A routed id may carry a provider prefix ("upstage/solar-pro4").
  const bare = id.slice(id.lastIndexOf('/') + 1).toLowerCase()
  if (bare.startsWith('deepseek-')) return <DeepSeekIcon className="text-[#4D6BFE]" />
  if (bare.startsWith('solar-')) return <UpstageIcon className="text-[#908AF9]" />
  if (/^(gemini|gemma)/.test(bare)) return <GeminiIcon />
  if (bare.startsWith('grok')) return <GrokIcon className="text-ink" />
  if (/^(kimi|moonshot)/.test(bare)) return <KimiIcon />
  if (/^(glm|z-ai|zai)/.test(bare)) return <ZaiIcon className="text-ink" />
  if (bare.startsWith('minimax')) return <MiniMaxIcon className="text-[#E73562]" />
  // OpenAI: "gpt-…", "chatgpt-…" and the o-series ("o3", "o4-mini").
  if (/^(gpt-|chatgpt|o\d)/.test(bare)) return <OpenAIIcon className="text-ink" />
  // Alibaba's Qwen family, with its QwQ/QVQ reasoning models.
  if (/^(qwen|qwq|qvq)/.test(bare)) return <QwenIcon className="text-[#615CED]" />
  // ByteDance's Doubao and Seed families.
  if (/^(doubao|seed-|bytedance)/.test(bare)) return <ByteDanceIcon />
  if (bare.startsWith('claude')) return <AnthropicIcon className="text-[#D97757]" />
  // Meta's Llama family, bare or with its "meta-" prefix.
  if (/^(llama|meta-)/.test(bare)) return <MetaIcon />
  // Tencent's Hunyuan family: "hy4flash-free", "hy-…", "hunyuan-…".
  if (/^(hy[\d-]|hunyuan)/.test(bare)) return <TencentCloudIcon />
  // The router's own models (group "Auto", or "tera-…" ids) wear the Tera Router logo.
  if (group?.trim().toLowerCase() === 'auto' || bare.startsWith('tera-'))
    return (
      <img
        alt=""
        className="size-6 mix-blend-multiply dark:mix-blend-screen dark:invert"
        height={24}
        src="/static/images/tera.png?v=3"
        width={24}
      />
    )
  return null
}
